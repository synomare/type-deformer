import assert from 'node:assert/strict';
import { createConformalSourcePool } from './source-pool.mjs';
const pool = createConformalSourcePool({ pointLimit: 10 });
let loads = 0;
const request = (key, count) => ({key, load(available) { loads++; assert.ok(available >= 0); return {pointCount:count}; }});
const a=request('a',6), b=request('b',6);
pool.sync([a,a,b]);assert.equal(pool.state().total,2);assert.equal(loads,0);
assert.equal(pool.inspect('a').status,'pending');assert.equal(pool.inspect('unknown').status,'missing');assert.equal(pool.state().total,2);
pool.setPaused(true);assert.equal(pool.advance(),false);pool.setPaused(false);
pool.advance();assert.equal(pool.read('a').pointCount,6);
assert.equal(pool.inspect('a').status,'ready');
pool.advance();assert.match(pool.state().error,/上限/);assert.equal(pool.read('b'),null);assert.equal(pool.read('a').pointCount,6);
assert.equal(pool.inspect('b').status,'error');assert.match(pool.inspect('b').error,/上限/);
pool.sync([a,b]);assert.equal(pool.advance(),false,'Stable failure must not cause an infinite render loop');
pool.sync([b]);pool.retry();pool.advance();assert.equal(pool.state().ready,1);assert.equal(pool.state().points,6);
pool.sync([b]);assert.equal(pool.advance(),false,'No rebuild for stable active glyph');
pool.sync([]);assert.equal(pool.state().points,0);assert.equal(pool.state().total,0);
pool.sync([{key:'bad',load(){throw new Error('test failure');}}]);pool.advance();assert.equal(pool.state().error,'test failure');
pool.reset();assert.equal(pool.state().error,'');assert.equal(pool.state().total,0);
console.log('Conformal source pool: lazy shared leases, pause, explicit budget/error, stable failure, retry, release and reset passed.');
