// Mechanical browser bundle of the already-verified independent solid kernels.
// No build dependency, dynamic import, CDN, or file:// worker URL is required.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const modules=['anamorphic-type/core.mjs','anamorphic-type/studio.mjs','anamorphic-type/surface.mjs','scroll-type/core.mjs'];
let body='const modules = Object.create(null);\n';
for(const name of modules){
  const source=fs.readFileSync(path.join(root,'.codex/prototypes',name),'utf8');
  const names=[...source.matchAll(/^export (?:const|function) (\w+)/gm)].map(m=>m[1]);
  if(!names.length)throw Error('No explicit exports: '+name);
  const code=source.replace(/^import \{([^}]+)\} from ['"]([^'"]+)['"];?\r?$/gm,(_,symbols,from)=>{
    const dependency=path.posix.normalize(path.posix.join(path.posix.dirname(name),from));
    if(!modules.includes(dependency)||modules.indexOf(dependency)>=modules.indexOf(name))throw Error('Unordered dependency '+dependency);
    return `const {${symbols}} = modules[${JSON.stringify(dependency)}];`;
  }).replace(/^export /gm,'');
  if(/^import |^export /m.test(code))throw Error('Unsupported module declaration: '+name);
  body+=`modules[${JSON.stringify(name)}] = (function () {\n${code}\nreturn {${names.join(',')}};\n})();\n`;
}
body+="return {scroll: modules['scroll-type/core.mjs'], anamorphic: modules['anamorphic-type/core.mjs'], surface: modules['anamorphic-type/surface.mjs']};";
const code=`/* Generated by scripts/build-sculpture.mjs. Source remains in .codex/prototypes. */\n(function(root){\n'use strict';\nfunction createEngine(){\n${body}\n}\nroot.TypeDeformerSculpture = {createEngine};\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
const target=path.join(root,'sculpture-engine.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==code)throw Error('Sculpture bundle is stale. Run node scripts/build-sculpture.mjs');
  console.log('Sculpture browser kernels match the tested prototype sources.');
}else{fs.writeFileSync(target,code);console.log('Generated sculpture-engine.js ('+code.length+' characters).');}
