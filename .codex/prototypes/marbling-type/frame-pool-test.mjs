import assert from 'node:assert/strict';
import { prepareMarblingGlyph, MARBLING_PRESETS } from './core.mjs';
import { compileMarblingGlyph, renderMarblingLod } from './lod.mjs';
import { createMarblingFramePool } from './frame-pool.mjs';

const glyph = prepareMarblingGlyph([{ points: Array.from({ length: 1024 }, (_, i) => ({ x: Math.cos(i * Math.PI / 512) * 70, y: Math.sin(i * Math.PI / 512) * 90 })) }]);
const compiled = compileMarblingGlyph(glyph), modes = Object.values(MARBLING_PRESETS), pool = createMarblingFramePool();
const requests = Array.from({ length: 300 }, (_, i) => ({ compiled, settings: modes[i % 3], phase: .23, tolerance: i % 5 === 0 ? .04 : .08 }));
const tickets = pool.sync(requests);
assert.equal(pool.state().total, 3);
assert.equal(pool.state().builds, 3);
assert.equal(tickets[0].status, 'pending');
pool.setPaused(true);
assert.equal(pool.advance(), false);
pool.setPaused(false);
while (pool.state().pending) pool.advance();
assert.equal(tickets.length, 300);
assert.ok(tickets.every(ticket => ticket.status === 'ready'));
for (let i = 0; i < 300; i++) {
  assert.equal(tickets[i].result, tickets[i % 3].result, 'copies share the exact immutable result');
  assert.equal(tickets[i].result.tolerance, .04, 'strictest destination quality wins');
}
const nativeOrder = tickets.map(t => t.result);
const reversed = pool.sync([...requests].reverse());
assert.deepEqual(reversed.map(t => t.result).reverse(), nativeOrder);
assert.equal(pool.state().builds, 3, 'same frame does not recompute');
for (let i = 0; i < 3; i++) assert.deepEqual(tickets[i].result, renderMarblingLod(compiled, modes[i], .23, { tolerance: .04 }));
const prior = pool.state();
assert.throws(() => pool.sync([...requests, { compiled, settings: modes[0], tolerance: NaN }]), /precision/);
assert.deepEqual(pool.state(), prior, 'invalid request does not clear live results');
const finer = pool.sync([{ ...requests[0], tolerance: .01 }, { ...requests[0], tolerance: .08 }]);
assert.equal(finer[0].status, 'pending');
assert.equal(finer[1].status, 'ready', 'coarse consumer keeps valid geometry during fine preparation');
assert.equal(finer[1].result, tickets[0].result);
while (pool.state().pending) pool.advance();
assert.equal(finer[0].result, finer[1].result);
assert.equal(finer[0].result.tolerance, .01);
const count = pool.state().builds;
pool.sync([{ ...requests[0], tolerance: .02 }]);
assert.equal(pool.state().builds, count, 'higher accuracy can be reused');
const old = pool.sync([{ compiled, settings: modes[0], phase: 0 }]);
while (pool.state().pending) pool.advance();
const seam = pool.sync([{ compiled, settings: modes[0], phase: 1 }]);
assert.equal(seam[0].result, old[0].result, 'no quantisation but exact modulo-one seam');
const staticTickets = pool.sync([{ compiled, settings: { ...modes[1], motion: 0 }, phase: .2 }, { compiled, settings: { ...modes[1], motion: 0 }, phase: .9 }]);
assert.equal(pool.state().total, 1);
while (pool.state().pending) pool.advance();
assert.equal(staticTickets[0].result, staticTickets[1].result);
const differentFont = compileMarblingGlyph(prepareMarblingGlyph([{ points: glyph.rings[0].points.map(p => ({ x: p.x * .9, y: p.y * 1.1 })) }]));
pool.sync([{ compiled, settings: modes[0] }, { compiled: differentFont, settings: modes[0] }]);
assert.equal(pool.state().total, 2, 'different source revision cannot reuse an old glyph');
pool.advance({ maxWork: 1 });
const empty = pool.sync([]);
assert.deepEqual(empty, []);
assert.equal(pool.state().pointUsage.total, 0);
assert.equal(pool.state().pending, false);
assert.equal(staticTickets[0].status, 'missing');
const over = createMarblingFramePool({ pointLimit: 20 });
const errors = over.sync([{ compiled, settings: modes[0] }, { compiled, settings: modes[1] }]);
let iterations = 0;
while (over.state().pending) { over.advance({ maxWork: 7 }); assert.ok(over.state().pointUsage.total <= 20); assert.ok(++iterations < 10000); }
assert.ok(errors.every(t => t.status === 'error'));
assert.ok(errors.every(t => t.result === null));
assert.equal(over.state().pointUsage.working, 0);
const builds = over.state().builds;
over.sync([{ compiled, settings: modes[0] }, { compiled, settings: modes[1] }]);
assert.equal(over.state().builds, builds, 'stable error does not loop automatic rebuild');
over.retry(); assert.equal(over.state().pending, true);
over.reset(); assert.equal(over.state().pointUsage.total, 0);
assert.equal(errors[0].status, 'missing');
assert.throws(() => createMarblingFramePool({ pointLimit: 2 }), /limit/);
const broken = createMarblingFramePool({ taskFactory: () => { throw new Error('source preparation failed'); } });
const unavailable = broken.sync([{ compiled, settings: modes[0] }]);
assert.equal(unavailable[0].status, 'error');
assert.match(unavailable[0].error.message, /source preparation/);
assert.equal(broken.state().pending, false);
broken.retry(); assert.equal(unavailable[0].status, 'error');
const coarseReference = renderMarblingLod(compiled, modes[0], 0, { tolerance: .2 });
const constrained = createMarblingFramePool({ pointLimit: coarseReference.pointCount + 5 });
const coarseTickets = constrained.sync([{ compiled, settings: modes[0], phase: 0, tolerance: .2 }]);
while (constrained.state().pending) constrained.advance();
const retainedCoarse = coarseTickets[0].result;
assert.ok(retainedCoarse);
const upgrade = constrained.sync([{ compiled, settings: modes[0], phase: 0, tolerance: .001 }, { compiled, settings: modes[0], phase: 0, tolerance: .2 }]);
while (constrained.state().pending) { constrained.advance(); assert.ok(constrained.state().pointUsage.total <= constrained.state().pointLimit); }
assert.equal(upgrade[0].status, 'error');
assert.equal(upgrade[1].status, 'ready');
assert.equal(upgrade[1].result, retainedCoarse, 'failed precision upgrade cannot discard a valid coarser consumer');
console.log('Marbling frame pool: 300 ordered tickets -> 3 immutable shapes; strictest precision, valid coarse upgrade, same-frame reuse, static/seam keys, different source revisions, transactional validation, active-point cap, cancellation, stable error/retry and reset passed. Not an editor or Canvas paint test.');
