import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {readManifestUnits, sourceManifests} from './source-reader.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const hash=value=>createHash('sha256').update(value).digest('hex');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const schema=Number(fs.readFileSync(path.join(root,'project-codec.js'),'utf8').match(/var VERSION = (\d+);/)[1]);
const paths=fs.readdirSync(root).filter(name=>name==='index.html'||/\.(js|css)$/.test(name)&&!['build-info.js','playwright.config.js'].includes(name));
for(const folder of ['assets/vendor','assets/presets']){
  for(const name of fs.readdirSync(path.join(root,folder))) if(/\.(js|mjs)$/.test(name))paths.push(folder+'/'+name);
}
for(const manifest of Object.values(sourceManifests)){
  paths.push(manifest);
  for(const unit of readManifestUnits(manifest,{root}))if(!paths.includes(unit.path))paths.push(unit.path);
}
paths.sort();
const canonicalText=file=>fs.readFileSync(file,'utf8').replace(/\r\n?/g,'\n');
const assets=Object.fromEntries(paths.map(name=>[name,hash(canonicalText(path.join(root,name)))]));
const rendererRevision=hash(JSON.stringify({appVersion:pkg.version,schemaVersion:schema,assets}));
const result={appVersion:pkg.version,schemaVersion:schema,rendererRevision,hashAlgorithm:'SHA-256',textNormalization:'UTF-8, CRLF/CR to LF',assets};
const output='// Generated by npm run build:info; content based, no timestamp.\n(function(root){\n  var info='+JSON.stringify(result,null,2)+';\n  Object.freeze(info.assets);root.TypeDeformerBuildInfo=Object.freeze(info);\n})(typeof globalThis!=="undefined"?globalThis:this);\n';
const target=path.join(root,'build-info.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||canonicalText(target)!==output)throw new Error('Runtime manifest is stale. Run npm run build:runtime after editing runtime sources.');
  console.log('Build info verified: '+rendererRevision.slice(0,16)+' / '+paths.length+' runtime sources');
}else{
  fs.writeFileSync(target,output);
  console.log('Build info generated: '+rendererRevision.slice(0,16)+' / '+paths.length+' runtime sources');
}
